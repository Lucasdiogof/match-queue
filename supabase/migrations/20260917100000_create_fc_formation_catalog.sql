-- Catalogo global de posicoes e formacoes. READ-ONLY para o usuario: nao
-- pertence a ninguem, todo mundo autenticado le, ninguem escreve pela API.
--
-- Por que no banco e nao num arquivo Dart: corrigir a coordenada de um slot
-- ou adicionar uma formacao nova da FC 27 passa a ser um update de linha, nao
-- um release da loja. O Flutter carrega o catalogo do backend e nunca inventa
-- slot proprio -- as RPCs validam contra estas tabelas.

create table public.fc_positions (
    code text primary key,
    sort_order integer not null
);

comment on table public.fc_positions is
    'Posicoes canonicas do EA FC. Catalogo global read-only.';

create table public.fc_formations (
    code text primary key,
    display_name text not null,
    is_active boolean not null default true,
    sort_order integer not null
);

comment on table public.fc_formations is
    'Formacoes disponiveis. Global, nunca por usuario.';

-- x: 0 = lateral esquerda, 1 = lateral direita.
-- y: 0 = proprio gol (goleiro), 1 = gol adversario.
-- Normalizado de proposito: pixel nao sobrevive a troca de tela, proporcao
-- sim. A UI decide o tamanho do campo e so multiplica.
create table public.fc_formation_slots (
    formation_code text not null
        references public.fc_formations (code) on delete cascade,
    slot_code text not null,
    position_code text not null references public.fc_positions (code),
    x numeric(4, 3) not null,
    y numeric(4, 3) not null,
    sort_order integer not null,

    primary key (formation_code, slot_code),
    constraint fc_formation_slots_x_range check (x >= 0 and x <= 1),
    constraint fc_formation_slots_y_range check (y >= 0 and y <= 1)
);

comment on column public.fc_formation_slots.y is
    '0 = proprio gol, 1 = gol adversario. A UI renderiza y=1 no topo.';

create index fc_formation_slots_formation_idx
    on public.fc_formation_slots (formation_code, sort_order);

alter table public.fc_positions enable row level security;
alter table public.fc_formations enable row level security;
alter table public.fc_formation_slots enable row level security;

-- Catalogo publico para quem esta logado. Sem policy de escrita em nenhuma
-- das tres: mudanca de catalogo e migration, nunca chamada de app.
create policy fc_positions_select_authenticated
    on public.fc_positions for select to authenticated using (true);
create policy fc_formations_select_authenticated
    on public.fc_formations for select to authenticated using (true);
create policy fc_formation_slots_select_authenticated
    on public.fc_formation_slots for select to authenticated using (true);

revoke all on table public.fc_positions from anon;
revoke all on table public.fc_formations from anon;
revoke all on table public.fc_formation_slots from anon;

grant select on table public.fc_positions to authenticated;
grant select on table public.fc_formations to authenticated;
grant select on table public.fc_formation_slots to authenticated;

